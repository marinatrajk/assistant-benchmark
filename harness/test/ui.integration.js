import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../src/server.js';

test('UI profile, task, memory, batch, inspector, review, and mobile layout work end-to-end',async()=>{
  const dir=await mkdtemp(join(tmpdir(),'relay-ui-'));
  const app=await createApp({dataDir:dir,port:0,modelCall:async()=>({output:[{type:'message',role:'assistant',content:[{type:'output_text',text:'UI test completed.'}]}],usage:{input_tokens:12,output_tokens:4}})});
  const executablePath=existsSync('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome')?'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome':undefined;
  const browser=await chromium.launch({headless:true,executablePath});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(app.url);
    await page.getByRole('button',{name:'Add your OpenAI API key'}).click();
    await page.locator('[name="apiKey"]').fill('ui-test-key');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Memory',exact:true}).click();
    await page.getByRole('button',{name:'Add memory'}).click();
    await page.locator('[name="content"]').fill('Prefers small, readable tools.');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('.memory-content').filter({hasText:'Prefers small'}).waitFor();
    await page.getByRole('button',{name:'Evaluations',exact:true}).click();
    await page.getByRole('button',{name:'New task'}).click();
    await page.locator('[name="name"]').fill('UI test task');
    await page.locator('[name="prompt"]').fill('Say UI test completed.');
    await page.locator('[name="checks"]').fill('[{"type":"response_contains","value":"UI test completed"}]');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    const checkedIds=await page.locator('[data-task]:checked').evaluateAll(elements=>elements.map(e=>e.dataset.task));
    for(const id of checkedIds)await page.locator(`[data-task="${id}"]`).uncheck();
    await page.locator('.task-card').filter({hasText:'UI test task'}).getByRole('checkbox').check();
    await page.getByRole('button',{name:'Run evaluation'}).click();
    await page.locator('.inspector .status.completed').waitFor();
    await page.locator('#review-score').selectOption('4');
    await page.locator('#review-notes').fill('The trace is clear.');
    await page.locator('.review-box').getByRole('button',{name:'Save',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#review-notes')?.value==='The trace is clear.');
    await page.getByRole('button',{name:'Close inspector'}).click();
    await page.getByRole('button',{name:'Results',exact:true}).click();
    await page.getByRole('heading',{name:'Model × task comparison'}).waitFor();
    await page.getByRole('button',{name:'Models',exact:true}).click();
    for (const name of ['Gemini 4 Argon','GPT-6 Astra','Claude Fable 5.1','Claude Opus 5.5']) await page.getByRole('heading',{name,exact:true}).waitFor();
    await page.locator('[data-edit-profile="gemini-4-argon"]').click();
    assert.equal(await page.locator('[name="enabled"]').isChecked(),false);
    assert.equal(await page.locator('[name="model"]').inputValue(),'');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    await page.locator('[data-edit-profile="openai"]').click();
    await page.locator('dialog summary').click();
    await page.locator('[name="maxOutputTokens"]').fill('4096');
    await page.locator('[name="reasoningEffort"]').selectOption('low');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    const state=await(await fetch(app.url+'/api/state')).json();
    assert.equal(state.profiles.find(p=>p.id==='openai').maxOutputTokens,4096);assert.equal(state.runs[0].metadata.review.score,4);
    await page.getByRole('button',{name:'Evaluations',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
  }finally{await browser.close();await app.close();await rm(dir,{recursive:true,force:true});}
});
